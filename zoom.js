export const MIN_ZOOM = 0.05, MAX_ZOOM = 32;

// Keep the scrollable image at its full display size, but rasterize only the
// visible tile. Enlarging a bounded thumbnail loses the very pixels we inspect.
export function previewTile(image, viewport, pixelRatio = 1) {
  const ratio = Math.max(1, Math.min(2, pixelRatio || 1)), padding = 64;
  const left = Math.max(0, Math.min(image.width - 1, Math.floor(viewport.left - image.left - padding)));
  const top = Math.max(0, Math.min(image.height - 1, Math.floor(viewport.top - image.top - padding)));
  const right = Math.max(left + 1, Math.min(image.width, Math.ceil(viewport.left + viewport.width - image.left + padding)));
  const bottom = Math.max(top + 1, Math.min(image.height, Math.ceil(viewport.top + viewport.height - image.top + padding)));
  return {left, top, width:right-left, height:bottom-top, pixelWidth:Math.ceil((right-left)*ratio), pixelHeight:Math.ceil((bottom-top)*ratio)};
}

// Pixel deltas retain the fine movements generated by trackpad pinch gestures.
// Normalize mouse wheel units and limit unusually large individual inputs.
export function wheelZoom(current, deltaY, deltaMode = 0, pageHeight = 800) {
  const scale = Math.max(MIN_ZOOM, Math.min(MAX_ZOOM, current));
  if (!Number.isFinite(deltaY) || deltaY === 0) return scale;
  const page = Number.isFinite(pageHeight) && pageHeight > 0 ? pageHeight : 800;
  const unit = deltaMode === 1 ? 16 : deltaMode === 2 ? page : 1;
  const change = Math.max(-0.06, Math.min(0.06, -deltaY * unit * 0.0024));
  return Math.max(MIN_ZOOM, Math.min(MAX_ZOOM, scale * Math.exp(change)));
}

export const zoomText = scale => `${Number((scale * 100).toFixed(1))}%`;
